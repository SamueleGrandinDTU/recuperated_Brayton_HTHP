"""Example showing the comparison of the four HTHP cycles (S-BR, S-IR, TES-BR, TES-IR)
in terms of T-s and hx diagrams, exergy destruction, component cost, exergetic efficiencies and LCOH.
Input data are the tables in results/paper/tables, generated by the single layouts."""

from matplotlib import pyplot as plt

from src import (
    plot_ts_diagram,
    plot_hx_diagram,
    plot_exergy_destruction_stacked,
    plot_component_cost_stacked,
    plot_exergetic_efficiencies,
    plot_exergy_plots,
    plot_lcoh_scenarios_stacked,
    plot_delta_lcoh_analysis,
    plot_lcoh_breakdown_stacked,
)

# 1. Load the tables of the four cycles (S-BR, S-IR, TES-BR, TES-IR) and their labels
cycle_labels = ["S-BR", "S-IR", "TES-BR", "TES-IR"]

connections = [
    "results/paper/tables/connections/S_BR_hthp_connections.csv",
    "results/paper/tables/connections/S_IR_hthp_connections.csv",
    "results/paper/tables/connections/TES_BR_hthp_connections.csv",
    "results/paper/tables/connections/TES_IR_hthp_connections.csv",
]

hx_tables = [
    "results/paper/tables/hx/S_BR_hthp_hx_table.csv",
    "results/paper/tables/hx/S_IR_hthp_hx_table.csv",
    "results/paper/tables/hx/TES_BR_hthp_hx_table.csv",
    "results/paper/tables/hx/TES_IR_hthp_hx_table.csv",
]

exergy_results = [
    "results/paper/tables/components_exergy/S_BR_hthp_exergy_components.csv",
    "results/paper/tables/components_exergy/S_IR_hthp_exergy_components.csv",
    "results/paper/tables/components_exergy/TES_BR_hthp_exergy_components.csv",
    "results/paper/tables/components_exergy/TES_IR_hthp_exergy_components.csv",
]

component_costs = [
    "results/paper/tables/components_cost/S_BR_hthp_components_cost.csv",
    "results/paper/tables/components_cost/S_IR_hthp_components_cost.csv",
    "results/paper/tables/components_cost/TES_BR_hthp_components_cost.csv",
    "results/paper/tables/components_cost/TES_IR_hthp_components_cost.csv",
]

lcoh_tables = [
    "results/paper/tables/lcoh/S_BR_hthp_lcoh.csv",
    "results/paper/tables/lcoh/S_IR_hthp_lcoh.csv",
    "results/paper/tables/lcoh/TES_BR_hthp_lcoh.csv",
    "results/paper/tables/lcoh/TES_IR_hthp_lcoh.csv",
]

lcoh_breakdowns = [
    "results/paper/tables/lcoh/S_BR_hthp_lcoh_breakdown.csv",
    "results/paper/tables/lcoh/S_IR_hthp_lcoh_breakdown.csv",
    "results/paper/tables/lcoh/TES_BR_hthp_lcoh_breakdown.csv",
    "results/paper/tables/lcoh/TES_IR_hthp_lcoh_breakdown.csv",
]

# 2. Plot the T-s diagrams: base vs intercooled, and standalone vs TES-integrated (eventually save them as PNG files)
plot_ts_diagram(
    [connections[0], connections[1]],
    cycle_labels=["S-BR", "S-IR"],
    save_path=None,
)

plot_ts_diagram(
    [
        [connections[0], connections[2]],  # base: standalone, TES-integrated
        [connections[1], connections[3]],  # intercooled: standalone, TES-integrated
    ],
    cycle_labels=[
        ["S-BR", "TES-BR"],
        ["S-IR", "TES-IR"],
    ],
    save_path=None,
)

# 3. Plot the hx diagrams of the standalone cycles (eventually save them as PNG files)
plot_hx_diagram(
    [
        [hx_tables[0]],
        [hx_tables[1]],
    ],
    save_path=None,
)

# 4. Compare the exergy destruction and the exergetic efficiencies (eventually save them as PNG files)
plot_exergy_destruction_stacked(
    exergy_results,
    cycle_labels=cycle_labels,
    save_path=None,
)

plot_exergetic_efficiencies(
    exergy_results,
    cycle_labels=cycle_labels,
    save_path=None,
)

plot_exergy_plots(
    exergy_results,
    cycle_labels=cycle_labels,
    plots=["destruction", "efficiencies"],
    combined=True,
    layout="horizontal",
    save_path=None,
)

# 5. Compare the component costs (eventually save them as PNG files)
plot_component_cost_stacked(
    component_costs,
    cycle_labels=cycle_labels,
    save_path=None,
)

# 6. Compare the LCOH of the scenarios on the DK1 market (fixed demand profile)
plot_lcoh_scenarios_stacked(
    lcoh_tables,
    lcoh_kind="DK1 fixed",
    cycle_labels=cycle_labels,
    save_path=None,
)

# 7. Plot the LCOH change due to the TES integration (TES-integrated - standalone), per scenario, market and heat demand
plot_delta_lcoh_analysis(
    [
        [lcoh_tables[0], lcoh_tables[2]],  # base
        [lcoh_tables[1], lcoh_tables[3]],  # intercooled
    ],
    pair_labels=["Base", "Intercooled"],
    save_path=None,
)

# 8. Plot the LCOH breakdown in the central scenario (DK1 and DE markets, fixed demand profile)
plot_lcoh_breakdown_stacked(
    lcoh_breakdowns,
    cycle_labels=cycle_labels,
    save_path=None,
)

plt.show()
